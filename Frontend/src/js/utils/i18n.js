export function getCurrentLanguage() {
  return localStorage.getItem("scos_language") || "en";
}

export function setLanguage(lang) {
  if (lang === "en" || lang === "am") {
    localStorage.setItem("scos_language", lang);
    applyTranslations();
    window.dispatchEvent(new CustomEvent("language:changed", { detail: { language: lang } }));
  }
}

export function getText(key) {
  const lang = getCurrentLanguage();
  return translations[lang]?.[key] || translations.en[key] || key;
}

export function applyTranslations() {
  const lang = getCurrentLanguage();
  const t = translations[lang] || translations.en;

  // 1. Attribute translation
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (key && t[key]) {
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        if (el.hasAttribute("placeholder")) {
          el.setAttribute("placeholder", t[key]);
        }
      } else {
        const icon = el.querySelector("i");
        if (icon) {
          const iconHtml = icon.outerHTML;
          el.innerHTML = `${iconHtml} ${t[key]}`;
        } else {
          el.textContent = t[key];
        }
      }
    }
  });

  // 2. Direct DOM Text mapping
  const targets = document.querySelectorAll("a, button, label, h1, h2, h3, h4, th, td, span, p");
  targets.forEach((el) => {
    if (el.children.length === 0 || (el.children.length === 1 && el.querySelector("i, svg"))) {
      const lastNode = el.childNodes[el.childNodes.length - 1];
      const rawText = lastNode?.nodeValue?.trim();
      if (!rawText) return;

      for (const [key, val] of Object.entries(directTextMap)) {
        if (rawText === val.en || rawText === val.am) {
          const newText = val[lang] || val.en;
          if (el.children.length === 1 && el.querySelector("i, svg")) {
            lastNode.nodeValue = " " + newText;
          } else {
            el.textContent = newText;
          }
          break;
        }
      }
    }
  });

  // 3. Update all dropdown selectors on the page
  document.querySelectorAll(".scos-lang-select, #langToggleSelect").forEach((select) => {
    select.value = lang;
  });
}

export function renderLangSwitcher(containerElement) {
  if (!containerElement) return;
  const currentLang = getCurrentLanguage();

  containerElement.innerHTML = `
    <div class="lang-switcher-widget" style="display: inline-flex; align-items: center; margin: 0 8px;">
      <select class="scos-lang-select" aria-label="Language Selector" style="background: rgba(255,255,255,0.95); color: #0f172a; border: 1px solid #cbd5e1; border-radius: 8px; font-weight: 600; cursor: pointer; padding: 4px 8px; font-size: 13px; outline: none;">
        <option value="en" ${currentLang === "en" ? "selected" : ""}>🇬🇧 English</option>
        <option value="am" ${currentLang === "am" ? "selected" : ""}>🇪🇹 አማርኛ</option>
      </select>
    </div>
  `;

  const selectEl = containerElement.querySelector(".scos-lang-select");
  if (selectEl) {
    selectEl.addEventListener("change", (e) => {
      setLanguage(e.target.value);
    });
  }
}

// Global window attachments
window.setLanguage = setLanguage;
window.applyTranslations = applyTranslations;
window.getCurrentLanguage = getCurrentLanguage;

document.addEventListener("DOMContentLoaded", () => {
  applyTranslations();

  // Listen to any language selector on page
  document.querySelectorAll(".scos-lang-select, #langToggleSelect").forEach((select) => {
    select.addEventListener("change", (e) => {
      setLanguage(e.target.value);
    });
  });

  const headerActions = document.querySelector(".nav-container, .navbar-header, .header-right, .top-nav, .user-profile-menu, .user-nav-links, .nav-auth");
  if (headerActions && !document.querySelector(".scos-lang-select")) {
    const wrapper = document.createElement("span");
    renderLangSwitcher(wrapper);
    headerActions.prepend(wrapper);
  }
});
